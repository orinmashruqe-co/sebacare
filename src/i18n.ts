import { Language, RelationType } from './types';

export function formatDigits(input: string | number, lang: Language): string {
  const str = String(input);
  if (lang !== 'bn') return str;
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return str.replace(/\d/g, (d) => bnDigits[Number(d)]);
}

export function translateRelation(rel: RelationType, custom: string | undefined, lang: Language): string {
  if (rel === 'Other' && custom) return custom;
  if (lang === 'en') return rel;
  const map: Record<RelationType, string> = {
    Self: 'নিজে',
    Father: 'বাবা',
    Mother: 'মা',
    Spouse: 'স্ত্রী/স্বামী',
    Child: 'সন্তান',
    Other: 'অন্যান্য',
  };
  return map[rel] || rel;
}

